#!/usr/bin/env python3
"""Verify removed dependencies and exact XDV parity; compare supported PDFs too."""
from pathlib import Path
import hashlib
import json
import subprocess

root=Path(__file__).resolve().parents[2]
manifest=root/'experiments/xetex-native/Cargo.toml'
frontend=root/'.build/xetex-native-target/release/xetex-native-probe'
backend=root/'.build/krilla-xdv-target/release/krilla-xdv-probe'
out=root/'.build/xetex-native-results'
out.mkdir(parents=True,exist_ok=True)
(out/'result.json').unlink(missing_ok=True)
tree=subprocess.check_output(['cargo','tree','--locked','--manifest-path',str(manifest),'-e','normal,build','--prefix','none'],text=True)
(out/'dependencies.txt').write_text(tree)
for forbidden in ('tectonic_pdf_io','tectonic_engine_xdvipdfmx'):
    if any(line.split()[0]==forbidden for line in tree.splitlines() if line.strip()):raise RuntimeError(f'Unexpected dependency {forbidden}')
features=json.loads((root/'profiles/features.json').read_text())['features']
cases=[root/p for paths in features.values() for p in paths]
# Generated by the PNG fixture preparation documented alongside the backend.
cases.append(root/'.build/xdv-probe/invoice-png.tex')
cases.extend(sorted((root/'experiments/krilla-xdv/fixtures').glob('*.tex')))
backend_cases={c['example'] for c in json.loads((root/'.build/xdv-probe/krilla-comparison.json').read_text())['results'] if c['compiled']}
results=[]
for src in cases:
    xdv=out/(src.stem+'.xdv')
    run=subprocess.run([str(frontend),str(root/'dist/bundles/full/texbundle'),str(src),str(xdv)],capture_output=True,text=True,timeout=60)
    (out/(src.stem+'.log')).write_text(run.stdout+run.stderr)
    if run.returncode:raise RuntimeError(f'{src.name} failed; see its log')
    reference=root/'.build/xdv-probe'/(src.stem+'.xdv')
    result={'example':src.stem,'xdv_matches':xdv.read_bytes()==reference.read_bytes(),'xdv_sha256':hashlib.sha256(xdv.read_bytes()).hexdigest()}
    if src.stem in backend_cases:
        pdf=out/(src.stem+'.pdf')
        subprocess.run([str(backend),str(xdv),str(root/'.build/krilla-fonts'),str(pdf),str(src.with_suffix('.assets'))],check=True,timeout=60)
        result['pdf_matches_reference_backend']=pdf.read_bytes()==(root/'.build/xdv-probe'/(src.stem+'-krilla.pdf')).read_bytes()
        result['pdf_sha256']=hashlib.sha256(pdf.read_bytes()).hexdigest()
    else:result['pdf_status']='backend unsupported; not passed'
    results.append(result)
report={'scope':'host experimental frontend/backend, not release acceptance','removed_dependencies':['tectonic_pdf_io','tectonic_engine_xdvipdfmx'],'frontend_sha256':hashlib.sha256(frontend.read_bytes()).hexdigest(),'results':results}
(out/'result.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
if not all(r['xdv_matches'] and r.get('pdf_matches_reference_backend',True) for r in results):raise SystemExit(1)
